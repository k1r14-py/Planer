from datetime import date

import pytest

from planer.dates import extract_deadline

MON = date(2026, 10, 19)  # понедельник


@pytest.mark.parametrize("text, title, expected", [
    ("Сдать отчёт до пятницы", "Сдать отчёт", date(2026, 10, 23)),
    ("отчёт к пятнице", "отчёт", date(2026, 10, 23)),
    ("отчёт к понедельнику", "отчёт", date(2026, 10, 26)),  # сегодня понедельник → следующий
    ("отчёт до следующей среды", "отчёт", date(2026, 10, 28)),
    ("позвонить до завтра", "позвонить", date(2026, 10, 20)),
    ("позвонить до послезавтра", "позвонить", date(2026, 10, 21)),
    ("купить билеты до 25 октября", "купить билеты", date(2026, 10, 25)),
    ("купить билеты к 5-го марта", "купить билеты", date(2027, 3, 5)),  # прошло → следующий год
    ("купить билеты до 25.10", "купить билеты", date(2026, 10, 25)),
    ("налоги до 01.12.2026", "налоги", date(2026, 12, 1)),
    ("ремонт, дедлайн пятница", "ремонт", date(2026, 10, 23)),
    ("ремонт срок до конца месяца", "ремонт", date(2026, 10, 31)),
    ("ремонт до конца недели", "ремонт", date(2026, 10, 25)),
    ("ремонт дедлайн через 3 дня", "ремонт", date(2026, 10, 22)),
    ("ремонт дедлайн через неделю", "ремонт", date(2026, 10, 26)),
    ("ремонт до следующей недели", "ремонт", date(2026, 10, 26)),
    ("закончить до вечера", "закончить", date(2026, 10, 19)),
])
def test_deadlines(text, title, expected):
    assert extract_deadline(text, MON) == (title, expected)


@pytest.mark.parametrize("text", [
    "дойти до магазина",
    "к врачу",
    "доделать отчёт",
    "до 32.13 ничего",
    "прочитать книгу",
])
def test_not_a_deadline(text):
    assert extract_deadline(text, MON) == (text, None)
